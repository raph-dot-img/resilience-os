//! Context-sensitive help text.

use resilience_core::mode::Mode;

use crate::app::HelpTopic;

const GENERAL: &[&str] = &[
    "== MOVING AROUND ==",
    "  Up / Down (or k / j)   Move the selection",
    "  Enter (or Right)       Open the selected item",
    "  Esc                    Go back one screen",
    "  1 - 9                  Open the numbered item directly",
    "  /                      Search everything",
    "  F1 or ?                This help",
    "  F5                     Detailed system status",
    "",
    "Every screen shows its most important keys on the bottom line.",
    "Ctrl-C does nothing here on purpose, so you cannot leave the interface by accident.",
    "",
];

pub fn lines(topic: HelpTopic, mode: Mode) -> Vec<String> {
    let specific: &[&str] = match topic {
        HelpTopic::Home => &[
            "== MAIN MENU ==",
            "  The left panel shows the state of the computer. Each line starts with a marker:",
            "    [OK] all good     [!!] needs attention     [--] information only",
            "  The right panel lists what you can do. Only sections that contain something",
            "  usable for your account are shown.",
            "  q                      Log out (asks for confirmation)",
        ],
        HelpTopic::Category => &[
            "== SECTIONS ==",
            "  The left side lists tools; the right side describes the selected one.",
            "  Items marked [UNAVAILABLE] are part of this system but their program is missing.",
            "  When a program runs, the interface waits for it. Quit the program normally",
            "  (for example Ctrl-X in nano, q in htop) to come back here.",
        ],
        HelpTopic::Reader => &[
            "== READING ==",
            "  Up / Down              Scroll one line",
            "  PgUp / PgDn / Space    Scroll one page",
            "  Home / End (g / G)     Jump to the start / end",
        ],
        HelpTopic::Notes => &[
            "== NOTES ==",
            "  n                      Create a new note and open it in the editor",
            "  Enter                  Open the selected note",
            "  r                      Refresh the list",
            "  In the editor (nano): Ctrl-O saves, Ctrl-X closes and returns here.",
            "  Notes are plain text files in the Notes folder of your home directory.",
        ],
        HelpTopic::Network => &[
            "== NETWORK ==",
            "  This screen reads the network state without sending anything.",
            "  p                      Test Internet access now (a few seconds at most)",
            "  r                      Re-read the network state",
            "  OFFLINE      no cable or wireless link",
            "  LOCAL LINK   connected to a local network without a route beyond it",
            "  ROUTE UP     a route exists, but the Internet is only confirmed by a probe",
        ],
        HelpTopic::Settings => &[
            "== SETTINGS ==",
            "  Enter                  Apply and save the selected theme or keyboard layout",
            "  The Monochrome theme uses no colour at all; all information stays visible.",
            "  A keyboard layout applies to every console of this computer until someone",
            "  logs out. Login prompts always use the system's layout, and your choice is",
            "  loaded again each time you log in.",
        ],
        HelpTopic::Users => &[
            "== USERS & SECURITY MODES ==",
            "  Lists the accounts of this computer and their security mode.",
            "  Enter                  Choose a new mode for the selected account",
            "  r                      Refresh the list",
            "  Every change shows its consequences first and then asks for the password of",
            "  an administrator (an Advanced account). Only type an administrator password",
            "  on a screen you trust. Changes are recorded in the audit log.",
            "  A mode is a set of real permissions of the account, not a display setting.",
        ],
        HelpTopic::Install => &[
            "== INSTALL RESILIENCE ==",
            "  Up/Down                Choose a line",
            "  Enter                  Change it: disk, encryption, keyboard, account name",
            "  m                      Next security mode of the selected account",
            "  f                      Full name of the selected account",
            "  a                      Add an account",
            "  d                      Remove the selected account",
            "  The last line, Install, shows a summary. Nothing is changed until you type",
            "  the disk's name there. The whole disk is erased. You then type the passwords",
            "  (and the encryption passphrase) yourself; they are never shown.",
        ],
        HelpTopic::Recovery => &[
            "== RECOVERY ==",
            "  Number / Enter         Open the selected item",
            "  In System generations: Enter makes the selected generation start at every",
            "  boot, after a confirmation and an administrator's password. It takes effect",
            "  at the next restart.",
            "  In Update from a USB stick (installed systems only): Enter opens a stick or",
            "  installs the update on it; c checks the update (intact, signed by a",
            "  Resilience release key) without installing anything; r refreshes the list.",
            "  Installing needs an administrator's password and is checked again first.",
            "  The new version starts at the next restart; the current one stays in the",
            "  boot menu and in System generations. Nothing else in this section changes",
            "  the system.",
            "  A system rollback (earlier generation) never touches your personal files;",
            "  restoring files is a separate operation.",
        ],
        HelpTopic::Backup => &[
            "== BACKUPS & USB STICKS ==",
            "  Only USB sticks and memory cards are listed; internal disks never are.",
            "  Enter                  Open the selected stick (it is mounted for you)",
            "  e                      Eject: finish writing, then it is safe to unplug",
            "  r                      Refresh the list (after plugging a stick in)",
            "  On a stick: the first line makes a new backup of your home folder; Enter on",
            "  a backup restores it into a new folder in Restored (nothing is overwritten);",
            "  c checks that a backup is intact without needing its passphrase.",
            "  Backups are encrypted with a passphrase you choose. Without it nobody can",
            "  open them, not even you: write it down and keep it apart from the stick.",
            "  Keep at least two copies, on different sticks, in different places.",
        ],
        HelpTopic::Library => &[
            "== OFFLINE LIBRARY & RESOURCE PACKS ==",
            "  Resource packs are large offline collections (Wikipedia, dictionaries, health",
            "  and practical guides). They are shared by every account of this computer.",
            "  In the Offline library:",
            "  Enter                  Read the selected pack in the text browser",
            "  s                      Search the full text of the selected pack",
            "  p                      Choose packs to get",
            "  In the text browser: Up/Down move between links, Enter or Right follows a",
            "  link, Left goes back, q quits and comes back here.",
            "  In Resource packs:",
            "  Space                  Tick or untick: [+] add, [-] remove, [*] installed",
            "  d                      Download the ticked packs (needs the Internet)",
            "  u                      Copy packs from a USB stick instead",
            "  f                      Show one language only, or all",
            "  Enter                  Details: size, license, source, fingerprint",
            "  Installing or removing asks for an administrator's password. Every file is",
            "  checked against its fingerprint (SHA-256) before it is installed. A download",
            "  stopped with Ctrl-C or by a lost connection continues where it stopped.",
        ],
        HelpTopic::Maps => &[
            "== MAPS ==",
            "  This list shows the maps of this computer: the built-in world overview,",
            "  installed map packs, and map files on an open USB stick.",
            "  Enter                  Open the map on the selected one",
            "  c                      Check a file on a USB stick against the catalog",
            "  u                      Open a USB stick to see the maps on it",
            "  p                      Choose map packs to get (Resource packs)",
            "  In the map:",
            "  Arrows                 Move (with Shift: one step at a time)",
            "  + / -                  Zoom in / out",
            "  d                      Coordinates in degrees, minutes and seconds",
            "  i                      What each map covers, its date, source and licence",
            "  L                      Legend: what the colours and signs mean",
            "  ?                      Every key        q   Back to this interface",
            "  The world overview has coasts, borders, large lakes and rivers and towns,",
            "  but no streets. Shaded areas have no detailed map installed. Maps can be",
            "  out of date or incomplete: something absent from the map may exist.",
        ],
        HelpTopic::Community => &[
            "== COMMUNITY NETWORK ==",
            "  Computers nearby can share their library, packs and pages. They appear here",
            "  a little after joining the same network (Wi-Fi, cable or the mesh).",
            "  Enter                  Open the selected computer (or the selected action)",
            "  a                      Type the address of a computer",
            "  r                      Refresh the list",
            "  A name in quotes with ? is only what that computer says about itself.",
            "  Packs you get from it are checked against this system's catalog before they",
            "  are installed; a pack that does not match is refused. Pages are not checked.",
            "  On the list of its packs: Space ticks, Enter gets the ticked packs.",
            "  On its shared folder: Enter copies a file into your Received folder.",
            "  Sharing this computer needs an administrator's password. Everything shared",
            "  can be read by anyone on that network. It stops when you stop it, when the",
            "  network changes, or when the computer restarts.",
        ],
        HelpTopic::Chat => &[
            "== LOCAL MESSAGES ==",
            "  Messages to people nearby, without the Internet: computers on the same",
            "  local network that have local messaging find each other.",
            "  Enter                  Open the conversation",
            "  n                      Write to an address someone gave you",
            "  p                      People heard on the local network",
            "  m                      My address, to give to others",
            "  In a conversation:",
            "  w                      Write a message (Enter sends, Ctrl-N starts a new line)",
            "  f                      Send a file (at most 900 KB; a copy is sent)",
            "  o                      Open the file of the selected message (read-only)",
            "  s                      Save it in your Received folder",
            "  c                      Give up on a message that is still waiting",
            "  a                      Give this person a name of your own",
            "  i                      Their whole address, to compare with them",
            "  What is shown beside each message is what is really known:",
            "    waiting     kept on this computer and tried again, for up to 7 days",
            "    sent        handed to the network; no proof that it arrived yet",
            "    delivered   their computer confirmed it has the message",
            "    FAILED      given up; the reason is shown",
            "  NOT VERIFIED on a message from them: it could not be checked against",
            "  their key (yet). A name in quotes with ? is only what an address claims.",
            "  A person is their address: compare it with them before trusting a name.",
            "  Messages are encrypted for the recipient. They travel on the local",
            "  network only. A message store on the network keeps them for people",
            "  who are away (\"sent, kept on the network\").",
        ],
        HelpTopic::Files => &[
            "== FIND & VIEW FILES ==",
            "  Type part of a file's name (several words: all must match). Your home folder",
            "  and open USB sticks are searched; hidden files are not.",
            "  Enter                  Show the file: text, PDF text, CSV table, archive",
            "                         contents, or a resource pack in the library",
            "  F3                     Size, date and SHA-256 checksum",
            "  F2                     Search again (after plugging in a stick)",
            "  In a table: arrows move between rows and columns, Esc goes back.",
            "  Nothing is ever changed, extracted or run from a file.",
        ],
        HelpTopic::Crypto => &[
            "== SECURITY & CRYPTOGRAPHY ==",
            "  Passphrases are always typed into the encryption program itself (age,",
            "  minisign), never into this interface: they are not shown or stored.",
            "  Choosing a file: type part of its name, Enter chooses it, Esc cancels.",
            "  Encrypt for: Space ticks a line, Enter encrypts. A passphrase, age keys or",
            "  OpenPGP keys: one kind per file. Tick 'Me' to be able to open it later.",
            "  OpenPGP (GnuPG) files and keys are recognised and handled automatically;",
            "  GnuPG asks its passphrases in a box on the screen.",
            "  Keys & contacts:",
            "  Enter                  Details, or create your keys",
            "  a / t                  Add a contact from a key file / by typing the key",
            "  g                      Create an OpenPGP (GnuPG) key, for GnuPG users",
            "  e                      Save your public keys on a USB stick",
            "  Delete                 Remove a contact",
            "  A forgotten passphrase cannot be recovered by anyone. Keys are included in",
            "  your encrypted backups. A signature proves who signed and that nothing",
            "  changed, not that a file is safe. Check new contacts' keys in person.",
        ],
        HelpTopic::Search => &[
            "== SEARCH ==",
            "  Type any word. Results include menu sections [MENU], built-in tools [TOOL],",
            "  applications [APP ] and handbook pages [DOC ]. Enter opens the selected result.",
        ],
    };
    let mode_text = format!("== YOUR MODE: {} ==", mode.label());
    let mut out: Vec<String> = specific.iter().map(|s| s.to_string()).collect();
    out.push(String::new());
    out.extend(GENERAL.iter().map(|s| s.to_string()));
    out.push(mode_text);
    out.push(format!("  {}", mode.description()));
    out.push(String::new());
    out.push("If the interface ever stops working, press Alt+F2 to reach another console,".into());
    out.push("or restart and choose an earlier system generation in the boot menu.".into());
    out
}
