    #[test]
    fn account_rules() {
        let none = BTreeSet::new();
        let acc = |n: &str, d: &str| NewAccount {
            name: n.into(),
            description: d.into(),
            mode: Mode::Stable,
        };
        assert_eq!(check_accounts(&default_accounts(), &none), Ok(()));
        assert_eq!(check_accounts(&[], &none), Err(Refusal::NoAccount));
        for (a, want) in [
            (acc("Bob", ""), Refusal::BadName("Bob".into())),
            (acc("_bob", ""), Refusal::BadName("_bob".into())),
            (acc("root", ""), Refusal::ReservedName("root".into())),
            (acc("nixbld7", ""), Refusal::ReservedName("nixbld7".into())),
            (
                acc("systemd-x", ""),
                Refusal::ReservedName("systemd-x".into()),
            ),
            (acc("bob", "a:b"), Refusal::BadDescription("bob".into())),
            (acc("bob", "a,b"), Refusal::BadDescription("bob".into())),
            (acc("bob", "a\nb"), Refusal::BadDescription("bob".into())),
            (
                acc("bob", &"x".repeat(61)),
                Refusal::BadDescription("bob".into()),
            ),
        ] {
            assert_eq!(check_accounts(&[a], &none), Err(want));
        }
        assert_eq!(
            check_accounts(&[acc("bob", ""), acc("bob", "")], &none),
            Err(Refusal::DuplicateName("bob".into()))
        );
        let many: Vec<NewAccount> = (0..9).map(|i| acc(&format!("u{i}"), "")).collect();
        assert_eq!(check_accounts(&many, &none), Err(Refusal::TooManyAccounts));
        let taken = names_in(
            "root:x:0:0::/root:/bin/sh\nmessagebus:x:4:4::/:/bin/false\navahi:x:5:5::/:\n",
        );
        assert_eq!(
            check_accounts(&[acc("avahi", "")], &taken),
            Err(Refusal::ReservedName("avahi".into()))
        );
        assert!(has_administrator(&default_accounts()));
        assert!(!has_administrator(&[acc("bob", "")]));
    }

