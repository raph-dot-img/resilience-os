/// The prebuilt systems the live ISO carries (ADR 0022 §1).
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Systems {
    pub uefi_plain: PathBuf,
    pub uefi_luks: PathBuf,
    pub bios_plain: PathBuf,
    pub bios_luks: PathBuf,
}

/// `/etc/resilience/install.toml`, generated by Nix: absolute tool paths
/// and the systems to copy. Nothing comes from the environment.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct InstallConfig {
    pub edition: String,
    /// This program, for the TUI to run it through pkexec.
    pub installer: PathBuf,
    pub lsblk: PathBuf,
    pub wipefs: PathBuf,
    pub sfdisk: PathBuf,
    pub udevadm: PathBuf,
    pub mkfs_vfat: PathBuf,
    pub mkfs_ext4: PathBuf,
    pub cryptsetup: PathBuf,
    pub mount: PathBuf,
    pub umount: PathBuf,
    pub nixos_install: PathBuf,
    pub nixos_enter: PathBuf,
    pub loadkeys: PathBuf,
    pub grub_install: PathBuf,
    pub sync: PathBuf,
    /// PATH given to nixos-install (it runs nix and coreutils itself).
    pub path: String,
    /// The layouts that may be chosen (as in system.toml).
    pub keymaps: Vec<String>,
    pub systems: Systems,
}

impl InstallConfig {
    pub fn parse(text: &str) -> Result<InstallConfig, String> {
        let c: InstallConfig = toml::from_str(text).map_err(|e| e.to_string())?;
        let s = &c.systems;
        for p in [
            &c.installer,
            &c.lsblk,
            &c.wipefs,
            &c.sfdisk,
            &c.udevadm,
            &c.mkfs_vfat,
            &c.mkfs_ext4,
            &c.cryptsetup,
            &c.mount,
            &c.umount,
            &c.nixos_install,
            &c.nixos_enter,
            &c.loadkeys,
            &c.grub_install,
            &c.sync,
            &s.uefi_plain,
            &s.uefi_luks,
            &s.bios_plain,
            &s.bios_luks,
        ] {
            if !p.is_absolute() {
                return Err(format!("path must be absolute: {}", p.display()));
            }
        }
        Ok(c)
    }

    /// The system to copy for this firmware and encryption choice.
    pub fn system(&self, firmware: Firmware, encrypt: bool) -> &PathBuf {
        let s = &self.systems;
        match (firmware, encrypt) {
            (Firmware::Uefi, false) => &s.uefi_plain,
            (Firmware::Uefi, true) => &s.uefi_luks,
            (Firmware::Bios, false) => &s.bios_plain,
            (Firmware::Bios, true) => &s.bios_luks,
        }
    }
}

/// How the machine started the live system, hence how it will boot.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Firmware {
    Uefi,
    Bios,
}

impl Firmware {
    pub fn id(self) -> &'static str {
        match self {
            Firmware::Uefi => "uefi",
            Firmware::Bios => "bios",
        }
    }
    pub fn parse(s: &str) -> Option<Firmware> {
        match s {
            "uefi" => Some(Firmware::Uefi),
            "bios" => Some(Firmware::Bios),
            _ => None,
        }
    }
    pub fn label(self) -> &'static str {
        match self {
            Firmware::Uefi => "UEFI (systemd-boot)",
            Firmware::Bios => "BIOS / legacy, and UEFI as a fallback (GRUB)",
        }
    }
}

/// A partition (or anything else) found on a disk, for the overview.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Part {
    pub path: String,
    pub size: u64,
    pub fstype: String,
    pub label: String,
    pub mountpoint: Option<String>,
}

/// A whole disk, offered or not.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Disk {
    pub path: String,
    pub size: u64,
    pub model: String,
    pub serial: String,
    pub transport: String,
    pub removable: bool,
    pub parts: Vec<Part>,
    /// Why it cannot be chosen; `None` means it can.
    pub problem: Option<String>,
}

impl Disk {
    /// "Samsung SSD 860 (500.1 GB, sata)" and similar.
    pub fn describe(&self) -> String {
        let model = if self.model.is_empty() {
            "unknown model"
        } else {
            &self.model
        };
        let mut s = format!("{model} ({}", human_size(self.size));
        if !self.transport.is_empty() {
            s.push_str(", ");
            s.push_str(&self.transport);
        }
        if self.removable {
            s.push_str(", removable");
        }
        s.push(')');
        s
    }

    /// The device name people type to confirm, such as `sda` or `nvme0n1`.
    pub fn name(&self) -> &str {
        self.path.strip_prefix("/dev/").unwrap_or(&self.path)
    }
}

/// Sizes in powers of 1000, as disk vendors print them.
pub fn human_size(bytes: u64) -> String {
    const UNITS: [&str; 5] = ["B", "kB", "MB", "GB", "TB"];
    let mut v = bytes as f64;
    let mut u = 0;
    while v >= 1000.0 && u + 1 < UNITS.len() {
        v /= 1000.0;
        u += 1;
    }
    if u == 0 {
        format!("{bytes} B")
    } else {
        format!("{v:.1} {}", UNITS[u])
    }
}

fn get(r: &BTreeMap<String, String>, k: &str) -> String {
    r.get(k).cloned().unwrap_or_default()
}

fn flag(r: &BTreeMap<String, String>, k: &str) -> bool {
    get(r, k) == "1"
}

/// Every whole disk in `lsblk -P -b -o LSBLK_COLUMNS` rows, with the reason
/// it cannot be chosen, if any. Loop devices, CD drives, RAM disks and
/// partitions are not disks and are left out.
pub fn disks(rows: &[BTreeMap<String, String>]) -> Vec<Disk> {
    let mut out = Vec::new();
    for row in rows.iter().filter(|r| get(r, "TYPE") == "disk") {
        let name = get(row, "NAME");
        let path = get(row, "PATH");
        if name.starts_with("zram") || name.starts_with("ram") {
            continue;
        }
        // Everything below this disk (partitions, LUKS, LVM...), walking down.
        let mut below = Vec::new();
        let mut frontier = vec![name.clone()];
        let mut depth = 0;
        while !frontier.is_empty() && depth < 8 {
            let children: Vec<&BTreeMap<String, String>> = rows
                .iter()
                .filter(|r| frontier.contains(&get(r, "PKNAME")))
                .collect();
            frontier = children.iter().map(|r| get(r, "NAME")).collect();
            below.extend(children);
            depth += 1;
        }
        let parts: Vec<Part> = below
            .iter()
            .map(|r| Part {
                path: get(r, "PATH"),
                size: get(r, "SIZE").parse().unwrap_or(0),
                fstype: get(r, "FSTYPE"),
                label: {
                    let l = get(r, "LABEL");
                    if l.is_empty() { get(r, "PARTLABEL") } else { l }
                },
                mountpoint: Some(get(r, "MOUNTPOINT")).filter(|m| !m.is_empty()),
            })
            .collect();
        let size: u64 = get(row, "SIZE").parse().unwrap_or(0);
        let in_use =
            !get(row, "MOUNTPOINT").is_empty() || parts.iter().any(|p| p.mountpoint.is_some());
        let problem = if !valid_device(&path) {
            Some("unusual device name".to_string())
        } else if flag(row, "RO") {
            Some("read-only".to_string())
        } else if in_use {
            Some("in use (the live system or a mounted drive is on it)".to_string())
        } else if size < MIN_DISK_BYTES {
            Some(format!(
                "too small ({}; at least {} needed)",
                human_size(size),
                human_size(MIN_DISK_BYTES)
            ))
        } else {
            None
        };
        out.push(Disk {
            path,
            size,
            model: get(row, "MODEL").trim().to_string(),
            serial: get(row, "SERIAL").trim().to_string(),
            transport: get(row, "TRAN"),
            removable: flag(row, "RM"),
            parts,
            problem,
        });
    }
    out
}

/// Path of partition `n` of `disk`: `/dev/sda` → `/dev/sda2`,
/// `/dev/nvme0n1` → `/dev/nvme0n1p2` (names ending in a digit take a `p`).
pub fn partition_path(disk: &str, n: u8) -> String {
    if disk.ends_with(|c: char| c.is_ascii_digit()) {
        format!("{disk}p{n}")
    } else {
        format!("{disk}{n}")
    }
}

/// The `sfdisk` script of ADR 0022 §3: GPT, BIOS boot 1 MiB, EFI system
/// partition 1 GiB, the root on the rest.
pub fn sfdisk_script() -> String {
    format!(
        "label: gpt\n\
         size=1MiB, type=21686148-6449-6E6F-744E-656564454649, name=\"bios\"\n\
         size=1GiB, type=C12A7328-F81F-11D2-BA4B-00A0C93EC93B, name=\"{BOOT_LABEL}\"\n\
         type=0FC63DAF-8483-4772-8E79-3D69D8477DE4, name=\"{ROOT_LABEL}\"\n"
    )
}

/// One account to create.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NewAccount {
    pub name: String,
    pub description: String,
    pub mode: Mode,
}

impl NewAccount {
    /// `NAME:MODE:DESCRIPTION`, the form passed on the command line.
    pub fn to_arg(&self) -> String {
        format!("{}:{}:{}", self.name, mode_id(self.mode), self.description)
    }

    pub fn from_arg(s: &str) -> Option<NewAccount> {
        let mut it = s.splitn(3, ':');
        let name = it.next()?.to_string();
        let mode = crate::admin::parse_mode(it.next()?)?;
        let description = it.next()?.to_string();
        Some(NewAccount {
            name,
            description,
            mode,
        })
    }
}

/// A description is shown in lists and stored in /etc/passwd's comment
/// field: printable, no `:`, short.
pub fn valid_description(d: &str) -> bool {
    d.chars().count() <= MAX_DESCRIPTION
        && d.chars()
            .all(|c| !c.is_control() && c != ':' && c != ',' && c != '\\')
}

/// Everything resilience-install needs, as the TUI builds it and the
/// installer re-checks it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Request {
    pub disk: String,
    /// Size and model seen in the summary: the installer refuses if the
    /// disk at that path is not the same any more.
    pub size: u64,
    pub model: String,
    pub firmware: Firmware,
    pub encrypt: bool,
    pub keymap: String,
    pub accounts: Vec<NewAccount>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Refusal {
    NoSuchDisk(String),
    DiskChanged(String),
    DiskUnusable(String, String),
    KeymapNotOffered(String),
    NoAccount,
    TooManyAccounts,
    BadName(String),
    ReservedName(String),
    DuplicateName(String),
    BadDescription(String),
    BadArguments(String),
}

impl fmt::Display for Refusal {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Refusal::NoSuchDisk(d) => write!(f, "there is no disk {d}"),
            Refusal::DiskChanged(d) => write!(
                f,
                "{d} is not the disk shown in the summary any more (size or model changed); \
                 nothing was changed"
            ),
            Refusal::DiskUnusable(d, why) => write!(f, "{d} cannot be used: {why}"),
            Refusal::KeymapNotOffered(k) => write!(f, "keyboard layout '{k}' is not offered"),
            Refusal::NoAccount => f.write_str("at least one account is needed"),
            Refusal::TooManyAccounts => {
                write!(
                    f,
                    "at most {MAX_ACCOUNTS} accounts can be created when installing"
                )
            }
            Refusal::BadName(n) => write!(
                f,
                "'{n}' is not a valid account name (lowercase letters, digits, - and _, \
                 starting with a letter, at most 32)"
            ),
            Refusal::ReservedName(n) => {
                write!(f, "'{n}' is used by the system; choose another name")
            }
            Refusal::DuplicateName(n) => write!(f, "'{n}' is listed twice"),
            Refusal::BadDescription(n) => write!(
                f,
                "the full name of '{n}' must be at most {MAX_DESCRIPTION} characters, \
                 without : , or \\"
            ),
            Refusal::BadArguments(why) => write!(f, "invalid request: {why}"),
        }
    }
}

/// Check the accounts. `taken` holds names already used by the new system
/// (its /etc/passwd and /etc/group), when known.
pub fn check_accounts(accounts: &[NewAccount], taken: &BTreeSet<String>) -> Result<(), Refusal> {
    if accounts.is_empty() {
        return Err(Refusal::NoAccount);
    }
    if accounts.len() > MAX_ACCOUNTS {
        return Err(Refusal::TooManyAccounts);
    }
    let mut seen = BTreeSet::new();
    for a in accounts {
        // Plain lowercase names only: valid_user_name also allows `_x`.
        if !valid_user_name(&a.name) || !a.name.starts_with(|c: char| c.is_ascii_lowercase()) {
            return Err(Refusal::BadName(a.name.clone()));
        }
        if RESERVED_NAMES.contains(&a.name.as_str())
            || a.name.starts_with("nixbld")
            || a.name.starts_with("systemd-")
            || taken.contains(&a.name)
        {
            return Err(Refusal::ReservedName(a.name.clone()));
        }
        if !seen.insert(a.name.clone()) {
            return Err(Refusal::DuplicateName(a.name.clone()));
        }
        if !valid_description(&a.description) {
            return Err(Refusal::BadDescription(a.name.clone()));
        }
    }
    Ok(())
}

/// Check a whole request against the disks present now and the offered
/// keyboard layouts.
pub fn check(req: &Request, present: &[Disk], keymaps: &[String]) -> Result<(), Refusal> {
    let disk = present
        .iter()
        .find(|d| d.path == req.disk)
        .ok_or_else(|| Refusal::NoSuchDisk(req.disk.clone()))?;
    if disk.size != req.size || disk.model != req.model {
        return Err(Refusal::DiskChanged(req.disk.clone()));
    }
    if let Some(why) = &disk.problem {
        return Err(Refusal::DiskUnusable(req.disk.clone(), why.clone()));
    }
    if !keymaps.contains(&req.keymap) || !crate::keyboard::is_valid_id(&req.keymap) {
        return Err(Refusal::KeymapNotOffered(req.keymap.clone()));
    }
    check_accounts(&req.accounts, &BTreeSet::new())
}

/// No Advanced account: nobody could change modes, install packs or
/// update the system later. Allowed, but the person is warned.
pub fn has_administrator(accounts: &[NewAccount]) -> bool {
    accounts.iter().any(|a| a.mode == Mode::Advanced)
}

/// The accounts proposed by default (ADR 0022 §7): an everyday Stable
/// account and an administrator used only to authorise.
pub fn default_accounts() -> Vec<NewAccount> {
    vec![
        NewAccount {
            name: "user".into(),
            description: "Everyday account".into(),
            mode: Mode::Stable,
        },
        NewAccount {
            name: "administrator".into(),
            description: "Authorises changes".into(),
            mode: Mode::Advanced,
        },
    ]
}

/// Command line of `resilience-install run` for a request (after the
/// program path).
pub fn to_args(req: &Request) -> Vec<String> {
    let mut v = vec![
        "run".to_string(),
        "--disk".into(),
        req.disk.clone(),
        "--size".into(),
        req.size.to_string(),
        "--model".into(),
        req.model.clone(),
        "--firmware".into(),
        req.firmware.id().into(),
        "--encrypt".into(),
        if req.encrypt { "yes" } else { "no" }.into(),
        "--keymap".into(),
        req.keymap.clone(),
    ];
    for a in &req.accounts {
        v.push("--account".into());
        v.push(a.to_arg());
    }
    v
}

/// Parse the arguments after `run`. Every option exactly once, except
/// `--account` (one per account).
pub fn parse_args(args: &[String]) -> Result<Request, Refusal> {
    let bad = |s: &str| Refusal::BadArguments(s.to_string());
    let mut one: BTreeMap<&str, String> = BTreeMap::new();
    let mut accounts = Vec::new();
    let mut it = args.iter();
    while let Some(opt) = it.next() {
        let val = it.next().ok_or_else(|| bad("an option has no value"))?;
        match opt.as_str() {
            "--account" => accounts.push(
                NewAccount::from_arg(val).ok_or_else(|| bad("--account is NAME:MODE:FULL NAME"))?,
            ),
            o @ ("--disk" | "--size" | "--model" | "--firmware" | "--encrypt" | "--keymap") => {
                if one.insert(o, val.clone()).is_some() {
                    return Err(bad("an option is given twice"));
                }
            }
            _ => return Err(bad("unknown option")),
        }
    }
    let mut take = |k: &str| one.remove(k).ok_or_else(|| bad("an option is missing"));
    let disk = take("--disk")?;
    if !valid_device(&disk) {
        return Err(bad("--disk must be a /dev path"));
    }
    let size = take("--size")?
        .parse()
        .map_err(|_| bad("--size is a number of bytes"))?;
    let model = take("--model")?;
    let firmware =
        Firmware::parse(&take("--firmware")?).ok_or_else(|| bad("--firmware is uefi or bios"))?;
    let encrypt = match take("--encrypt")?.as_str() {
        "yes" => true,
        "no" => false,
        _ => return Err(bad("--encrypt is yes or no")),
    };
    let keymap = take("--keymap")?;
    Ok(Request {
        disk,
        size,
        model,
        firmware,
        encrypt,
        keymap,
        accounts,
    })
}

/// The accounts file and mode overrides written into the new system.
pub fn account_state(accounts: &[NewAccount], now: &str) -> (LocalAccounts, ModeState) {
    let mut local = LocalAccounts::default();
    let mut modes = ModeState::default();
    for a in accounts {
        local.users.insert(
            a.name.clone(),
            LocalAccount {
                description: a.description.clone(),
            },
        );
        if a.mode != Mode::UltraStable {
            modes.users.insert(
                a.name.clone(),
                Override {
                    mode: a.mode,
                    declared: Mode::UltraStable,
                    changed: now.to_string(),
                    by: "resilience-install".to_string(),
                },
            );
        }
    }
    (local, modes)
}

/// Names in an /etc/passwd or /etc/group file.
pub fn names_in(file: &str) -> BTreeSet<String> {
    file.lines()
        .filter_map(|l| l.split(':').next())
        .filter(|n| !n.is_empty())
        .map(str::to_string)
        .collect()
}

