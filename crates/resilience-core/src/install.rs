    #[test]
    fn config_needs_absolute_paths() {
        let mut text = String::from(
            "edition = \"standard\"\npath = \"/run/current-system/sw/bin\"\nkeymaps = [\"us\"]\n",
        );
        for k in [
            "installer",
            "lsblk",
            "wipefs",
            "sfdisk",
            "udevadm",
            "mkfs_vfat",
            "mkfs_ext4",
            "cryptsetup",
            "mount",
            "umount",
            "nixos_install",
            "nixos_enter",
            "loadkeys",
            "grub_install",
            "sync",
        ] {
            text.push_str(&format!("{k} = \"/nix/store/x/bin/{k}\"\n"));
        }
        text.push_str("[systems]\n");
        for k in ["uefi_plain", "uefi_luks", "bios_plain", "bios_luks"] {
            text.push_str(&format!("{k} = \"/nix/store/{k}\"\n"));
        }
        let c = InstallConfig::parse(&text).expect("valid");
        assert_eq!(
            c.system(Firmware::Bios, true),
            &PathBuf::from("/nix/store/bios_luks")
        );
        assert_eq!(
            c.system(Firmware::Uefi, false),
            &PathBuf::from("/nix/store/uefi_plain")
        );
        assert!(InstallConfig::parse(&text.replace("/nix/store/x/bin/sfdisk", "sfdisk")).is_err());
        assert!(InstallConfig::parse(&format!("{text}extra = 1\n")).is_err());
    }

