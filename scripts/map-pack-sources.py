#!/usr/bin/env python3
"""Fetched Geofabrik extracts -> nix/maps/regional.nix (catalog map packs).

Usage: python3 -I scripts/map-pack-sources.py SOURCES.txt > nix/maps/regional.nix
SOURCES.txt lines: ID FILE PBF-SRI POLY-SRI YYYY-MM-DD SIZE DATED-URL
(written by the fetch step: dated file from the "latest" redirect, MD5 checked).
Names, coverage texts and which regions touch the sea are in TABLE below.
"""
import sys

MIRROR = "https://mirror.canevet.eu/files/resilience/packs/maps/sources/"
# id: (name, country, coast?, coverage detail)
TABLE = {
    "alsace": ("Alsace", "France", False, "Bas-Rhin, Haut-Rhin"),
    "aquitaine": ("Aquitaine", "France", True, "Dordogne, Gironde, Landes, Lot-et-Garonne, Pyrénées-Atlantiques"),
    "auvergne": ("Auvergne", "France", False, "Allier, Cantal, Haute-Loire, Puy-de-Dôme"),
    "basse-normandie": ("Basse-Normandie", "France", True, "Calvados, Manche, Orne"),
    "bourgogne": ("Bourgogne", "France", False, "Côte-d'Or, Nièvre, Saône-et-Loire, Yonne"),
    "centre": ("Centre-Val de Loire", "France", False, "Cher, Eure-et-Loir, Indre, Indre-et-Loire, Loir-et-Cher, Loiret"),
    "champagne-ardenne": ("Champagne-Ardenne", "France", False, "Ardennes, Aube, Marne, Haute-Marne"),
    "corse": ("Corse", "France", True, "Corse-du-Sud, Haute-Corse"),
    "franche-comte": ("Franche-Comté", "France", False, "Doubs, Jura, Haute-Saône, Territoire de Belfort"),
    "haute-normandie": ("Haute-Normandie", "France", True, "Eure, Seine-Maritime"),
    "ile-de-france": ("Île-de-France", "France", False, "Paris and the seven départements around it"),
    "languedoc-roussillon": ("Languedoc-Roussillon", "France", True, "Aude, Gard, Hérault, Lozère, Pyrénées-Orientales"),
    "limousin": ("Limousin", "France", False, "Corrèze, Creuse, Haute-Vienne"),
    "lorraine": ("Lorraine", "France", False, "Meurthe-et-Moselle, Meuse, Moselle, Vosges"),
    "midi-pyrenees": ("Midi-Pyrénées", "France", False, "Ariège, Aveyron, Haute-Garonne, Gers, Lot, Hautes-Pyrénées, Tarn, Tarn-et-Garonne"),
    "nord-pas-de-calais": ("Nord-Pas-de-Calais", "France", True, "Nord, Pas-de-Calais"),
    "pays-de-la-loire": ("Pays de la Loire", "France", True, "Loire-Atlantique, Maine-et-Loire, Mayenne, Sarthe, Vendée"),
    "picardie": ("Picardie", "France", True, "Aisne, Oise, Somme"),
    "poitou-charentes": ("Poitou-Charentes", "France", True, "Charente, Charente-Maritime, Deux-Sèvres, Vienne"),
    "provence-alpes-cote-d-azur": ("Provence-Alpes-Côte d'Azur", "France", True, "Alpes-de-Haute-Provence, Hautes-Alpes, Alpes-Maritimes, Bouches-du-Rhône, Var, Vaucluse"),
    "rhone-alpes": ("Rhône-Alpes", "France", False, "Ain, Ardèche, Drôme, Isère, Loire, Rhône, Savoie, Haute-Savoie"),
    "belgium": ("Belgium", None, True, "the whole country"),
    "switzerland": ("Switzerland", None, False, "the whole country"),
}

out = ["# Generated by scripts/map-pack-sources.py: do not edit by hand.",
       "# Geofabrik extracts pinned by hash; the mirror keeps unchanged copies",
       "# (Geofabrik drops old daily extracts). ODbL 1.0, (c) OpenStreetMap contributors.",
       "{ fetchurl, sea, seaSource }:", "{"]
for line in open(sys.argv[1], encoding="utf-8"):
    rid, f, pbf, poly, date, size, dated = line.split()
    name, country, coast, detail = TABLE[rid]
    full = f"{name}, {country}" if country else name
    poly_url = dated.rsplit("/", 1)[0] + f"/{rid}.poly"
    out += [
        f'  {rid} = {{',
        f'    id = "{rid}";',
        f'    name = "{name}";',
        f'    description = "OpenStreetMap data for {full} (Geofabrik extract of {date})";',
        f'    coverage = "{full}: {detail} (Geofabrik extract boundary)";',
        f'    pbf = fetchurl {{ urls = [ "{dated}" "{MIRROR}{f}" ]; hash = "{pbf}"; }};',
        f'    sourceName = "{f}";',
        f'    poly = fetchurl {{ urls = [ "{poly_url}" "{MIRROR}{rid}.poly" ]; hash = "{poly}"; }};',
        f'    dataDate = "{date}";',
    ]
    if coast:
        out += ["    inherit sea seaSource;"]
    out += ["  };"]
out.append("}")
print("\n".join(out))
